/// Compile-time encrypted strings to prevent static analysis.
/// All sensitive strings (DLL names, API names, paths, commands) are stored
/// as XOR-encrypted byte arrays and decrypted at runtime.
///
/// Feature-gated behind `evasion`.

const XOR_KEY: u8 = 0x5A;

/// Decrypt a XOR-encrypted byte slice into a String.
pub fn d(data: &[u8]) -> String {
    String::from_utf8(data.iter().map(|b| b ^ XOR_KEY).collect()).unwrap_or_default()
}

/// Decrypt a XOR-encrypted byte slice into a Vec<u8> (for C strings needing null terminator).
pub fn d_bytes(data: &[u8]) -> Vec<u8> {
    data.iter().map(|b| b ^ XOR_KEY).collect()
}

/// Decrypt and return as null-terminated C string bytes.
pub fn d_cstr(data: &[u8]) -> Vec<u8> {
    let mut v: Vec<u8> = data.iter().map(|b| b ^ XOR_KEY).collect();
    v.push(0);
    v
}

